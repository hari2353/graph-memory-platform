"""Human-readable memory audit — the 'can a person read and fix it?'
column every 2026 memory comparison scores. inspect_user renders one
user's projected memory as bounded Markdown: active facts grouped by
kind with validity instants and weights, plus the forget ledger (what
was superseded, when) so silence is never mistaken for absence."""
from __future__ import annotations

from graph_memory.core.types import TenantId, UserKey
from graph_memory.projector.engine import Projector

_MAX_FACTS = 100
_MAX_FORGETS = 50


def inspect_user(engine: Projector, tenant: TenantId, user: UserKey) -> str:
    """Render one user's memory as a bounded Markdown audit."""
    gateway = engine.gateway
    rows = sorted(
        gateway.observations(tenant, user),
        key=lambda r: (r.kind, r.target, r.valid_at),
    )
    directives = sorted(
        gateway.forget_directives(tenant, user),
        key=lambda d: (d.kind, d.target or "", d.forget_at),
    )
    lines = [
        f"# Memory audit — {tenant} / {user}",
        "",
        f"Generated by projection at {engine.clock.now().isoformat()}.",
        "",
    ]
    if rows:
        lines.append("## Active memory")
        lines.append("")
        lines.append("| kind | target | since | weight | half-life (days) |")
        lines.append("|---|---|---|---|---|")
        for row in rows[:_MAX_FACTS]:
            lines.append(
                f"| {row.kind} | {row.target} | {row.valid_at.date().isoformat()}"
                f" | {row.weight:.3g} | {row.half_life_days:g} |"
            )
        if len(rows) > _MAX_FACTS:
            lines.append(f"| … | {len(rows) - _MAX_FACTS} more facts truncated | | | |")
        lines.append("")
    else:
        lines.append("## Active memory")
        lines.append("")
        lines.append("_No active facts._")
        lines.append("")
    if directives:
        lines.append("## Forget ledger (superseded, never deleted)")
        lines.append("")
        lines.append("| kind | target | forgotten at |")
        lines.append("|---|---|---|")
        for directive in directives[:_MAX_FORGETS]:
            target = directive.target if directive.target is not None else "(whole kind)"
            lines.append(
                f"| {directive.kind} | {target}"
                f" | {directive.forget_at.date().isoformat()} |"
            )
        if len(directives) > _MAX_FORGETS:
            lines.append(
                f"| … | {len(directives) - _MAX_FORGETS} more directives truncated | |"
            )
        lines.append("")
    return "\n".join(lines)
